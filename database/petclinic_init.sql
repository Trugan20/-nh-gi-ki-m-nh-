-- Pet Clinic MySQL bootstrap script (v2)
-- Includes doctor management module and expanded sample data

CREATE DATABASE IF NOT EXISTS petclinic
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE petclinic;

CREATE TABLE users (
  id CHAR(36) PRIMARY KEY DEFAULT (UUID()),
  email TEXT NOT NULL,
  name TEXT NOT NULL,
  role ENUM('admin', 'veterinarian', 'receptionist', 'customer') NOT NULL DEFAULT 'customer',
  phone TEXT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE doctors (
  id CHAR(36) PRIMARY KEY,
  specialization TEXT NOT NULL,
  license_number VARCHAR(64) NOT NULL,
  years_experience INT NOT NULL DEFAULT 0,
  consultation_fee DECIMAL(10,2) NOT NULL DEFAULT 0,
  bio TEXT NULL,
  is_available BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_doctors_user FOREIGN KEY (id) REFERENCES users(id)
);

CREATE TABLE customers (
  id CHAR(36) PRIMARY KEY DEFAULT (UUID()),
  user_id CHAR(36) NULL,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT NOT NULL,
  address TEXT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_customers_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE pets (
  id CHAR(36) PRIMARY KEY DEFAULT (UUID()),
  customer_id CHAR(36) NOT NULL,
  name TEXT NOT NULL,
  species TEXT NOT NULL,
  breed TEXT NULL,
  age INT NULL,
  weight DECIMAL(5,2) NULL,
  gender TEXT NULL,
  microchip TEXT NULL,
  image_url TEXT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_pets_customer FOREIGN KEY (customer_id) REFERENCES customers(id)
);

CREATE TABLE appointments (
  id CHAR(36) PRIMARY KEY DEFAULT (UUID()),
  pet_id CHAR(36) NOT NULL,
  customer_id CHAR(36) NOT NULL,
  veterinarian_id CHAR(36) NULL,
  appointment_date TIMESTAMP NOT NULL,
  appointment_type TEXT NOT NULL,
  status ENUM('pending', 'confirmed', 'urgent', 'cancelled', 'completed') NOT NULL DEFAULT 'pending',
  notes TEXT NULL,
  reminder_sent_at TIMESTAMP NULL,
  reminder_channel ENUM('email', 'sms') NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_appointments_pet FOREIGN KEY (pet_id) REFERENCES pets(id),
  CONSTRAINT fk_appointments_customer FOREIGN KEY (customer_id) REFERENCES customers(id),
  CONSTRAINT fk_appointments_vet FOREIGN KEY (veterinarian_id) REFERENCES users(id)
);

CREATE TABLE medical_records (
  id CHAR(36) PRIMARY KEY DEFAULT (UUID()),
  pet_id CHAR(36) NOT NULL,
  appointment_id CHAR(36) NULL,
  veterinarian_id CHAR(36) NOT NULL,
  visit_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  symptoms TEXT NULL,
  diagnosis TEXT NULL,
  treatment TEXT NULL,
  notes TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_medical_pet FOREIGN KEY (pet_id) REFERENCES pets(id),
  CONSTRAINT fk_medical_appointment FOREIGN KEY (appointment_id) REFERENCES appointments(id),
  CONSTRAINT fk_medical_vet FOREIGN KEY (veterinarian_id) REFERENCES users(id)
);

CREATE TABLE inventory (
  id CHAR(36) PRIMARY KEY DEFAULT (UUID()),
  code TEXT NOT NULL,
  name TEXT NOT NULL,
  category TEXT NOT NULL,
  unit TEXT NOT NULL,
  stock INT NOT NULL DEFAULT 0,
  min_stock INT NOT NULL DEFAULT 10,
  price DECIMAL(10,2) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE prescriptions (
  id CHAR(36) PRIMARY KEY DEFAULT (UUID()),
  medical_record_id CHAR(36) NOT NULL,
  medicine_id CHAR(36) NOT NULL,
  quantity INT NOT NULL,
  dosage TEXT NULL,
  instructions TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_prescription_record FOREIGN KEY (medical_record_id) REFERENCES medical_records(id),
  CONSTRAINT fk_prescription_medicine FOREIGN KEY (medicine_id) REFERENCES inventory(id)
);

CREATE TABLE stock_batches (
  id CHAR(36) PRIMARY KEY DEFAULT (UUID()),
  inventory_id CHAR(36) NOT NULL,
  batch_number TEXT NOT NULL,
  quantity INT NOT NULL,
  expiry_date TIMESTAMP NOT NULL,
  supplier TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_stock_inventory FOREIGN KEY (inventory_id) REFERENCES inventory(id)
);

CREATE TABLE invoices (
  id CHAR(36) PRIMARY KEY DEFAULT (UUID()),
  customer_id CHAR(36) NOT NULL,
  appointment_id CHAR(36) NULL,
  invoice_number TEXT NOT NULL,
  total_amount DECIMAL(10,2) NOT NULL,
  status ENUM('pending', 'paid', 'overdue', 'cancelled') NOT NULL DEFAULT 'pending',
  issued_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  due_date TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_invoice_customer FOREIGN KEY (customer_id) REFERENCES customers(id),
  CONSTRAINT fk_invoice_appointment FOREIGN KEY (appointment_id) REFERENCES appointments(id)
);

CREATE TABLE invoice_items (
  id CHAR(36) PRIMARY KEY DEFAULT (UUID()),
  invoice_id CHAR(36) NOT NULL,
  inventory_id CHAR(36) NULL,
  description TEXT NOT NULL,
  quantity INT NOT NULL,
  unit_price DECIMAL(10,2) NOT NULL,
  total_price DECIMAL(10,2) NOT NULL,
  CONSTRAINT fk_invoice_item_invoice FOREIGN KEY (invoice_id) REFERENCES invoices(id),
  CONSTRAINT fk_invoice_item_inventory FOREIGN KEY (inventory_id) REFERENCES inventory(id)
);

CREATE TABLE payments (
  id CHAR(36) PRIMARY KEY DEFAULT (UUID()),
  invoice_id CHAR(36) NOT NULL,
  amount DECIMAL(10,2) NOT NULL,
  payment_method ENUM('cash', 'card', 'bank_transfer', 'e_wallet') NOT NULL,
  payment_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  notes TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_payment_invoice FOREIGN KEY (invoice_id) REFERENCES invoices(id)
);

CREATE TABLE camera_streams (
  id CHAR(36) PRIMARY KEY DEFAULT (UUID()),
  pet_id CHAR(36) NOT NULL,
  stream_url TEXT NOT NULL,
  room_number TEXT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_camera_pet FOREIGN KEY (pet_id) REFERENCES pets(id)
);

CREATE TABLE doctor_shifts (
  id CHAR(36) PRIMARY KEY DEFAULT (UUID()),
  veterinarian_id CHAR(36) NOT NULL,
  shift_date TIMESTAMP NOT NULL,
  start_time TEXT NOT NULL,
  end_time TEXT NOT NULL,
  status ENUM('planned', 'completed', 'off') NOT NULL DEFAULT 'planned',
  notes TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_shift_vet FOREIGN KEY (veterinarian_id) REFERENCES users(id)
);

CREATE TABLE appointment_reminders (
  id CHAR(36) PRIMARY KEY DEFAULT (UUID()),
  appointment_id CHAR(36) NOT NULL,
  channel ENUM('email', 'sms') NOT NULL,
  recipient TEXT NOT NULL,
  status TEXT NOT NULL,
  error TEXT NULL,
  sent_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_reminder_appointment FOREIGN KEY (appointment_id) REFERENCES appointments(id)
);

